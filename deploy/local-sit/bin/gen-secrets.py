#!/usr/bin/env python3
"""Create private runtime secrets for the isolated local SIT stack.

Writes, outside the repository and with owner-only permissions:

  $MARLEY_SIT_STATE_DIR (default: ~/.local/state/marley-sit)
    compose.env      variables consumed by deploy/local-sit/compose.yaml
    credentials.json site, admin and synthetic account credentials
    deployment.log   private deployment/verification log (appended to)

and creates the repository-side symlink deploy/local-sit/.env -> compose.env so
`docker compose -f deploy/local-sit/compose.yaml ...` finds the private values.
No secret is printed. Re-running without --force keeps existing secrets.
"""

from __future__ import annotations

import json
import os
import secrets
import sys
from pathlib import Path

SITE = "marley-sit.local"
ORIGIN = "http://127.0.0.1:18081"

USERS = [
    {
        "email": "sit.doc@example.invalid",
        "first_name": "SIT Doctor",
        "clinic_code": "DOC",
        "roles": ["Physician"],
        "password_var": "SIT_DOC_PASSWORD",
    },
    {
        "email": "sit.nur@example.invalid",
        "first_name": "SIT Nurse",
        "clinic_code": "NUR",
        "roles": ["Nursing User"],
        "password_var": "SIT_NUR_PASSWORD",
    },
    {
        "email": "sit.rec@example.invalid",
        "first_name": "SIT Reception",
        "clinic_code": "REC",
        "roles": ["Healthcare Administrator"],
        "password_var": "SIT_REC_PASSWORD",
    },
]


def main() -> int:
    force = "--force" in sys.argv[1:]
    repo_root = Path(__file__).resolve().parents[3]
    state_dir = Path(
        os.environ.get("MARLEY_SIT_STATE_DIR", Path.home() / ".local/state/marley-sit")
    )
    state_dir.mkdir(parents=True, exist_ok=True)
    os.chmod(state_dir, 0o700)

    compose_env = state_dir / "compose.env"
    credentials_path = state_dir / "credentials.json"
    log_path = state_dir / "deployment.log"

    if compose_env.exists() and not force:
        print(f"Secrets already exist at {state_dir}; not overwritten.")
        _ensure_symlink(repo_root, compose_env)
        print(f"Private state directory: {state_dir}")
        return 0

    values = {
        "DB_ROOT_PASSWORD": secrets.token_hex(24),
        "SIT_ADMIN_PASSWORD": secrets.token_hex(24),
        "SIT_EPOCH_SECRET": secrets.token_hex(32),
    }
    for user in USERS:
        values[user["password_var"]] = secrets.token_hex(16)

    lines = [
        "# Private runtime secrets for the isolated marley-sit stack.",
        "# Generated by deploy/local-sit/bin/gen-secrets.py; never commit.",
        f"SIT_SITE={SITE}",
        f"SIT_ORIGIN={ORIGIN}",
    ]
    lines += [f"{key}={value}" for key, value in values.items()]

    _write_private(compose_env, "\n".join(lines) + "\n")

    credentials = {
        "site": SITE,
        "origin": ORIGIN,
        "admin": {"user": "Administrator", "password": values["SIT_ADMIN_PASSWORD"]},
        "users": [
            {
                "email": user["email"],
                "first_name": user["first_name"],
                "clinic_code": user["clinic_code"],
                "roles": user["roles"],
                "password": values[user["password_var"]],
            }
            for user in USERS
        ],
    }
    _write_private(credentials_path, json.dumps(credentials, indent=2) + "\n")
    log_path.touch(mode=0o600, exist_ok=True)
    os.chmod(log_path, 0o600)

    _ensure_symlink(repo_root, compose_env)

    print(f"Private state directory: {state_dir}")
    print(f"Created {compose_env.name}, {credentials_path.name}, {log_path.name} (mode 600)")
    print(f"Linked deploy/local-sit/.env -> {compose_env}")
    print("No secret values were printed.")
    return 0


def _write_private(path: Path, text: str) -> None:
    flags = os.O_WRONLY | os.O_CREAT | os.O_TRUNC
    fd = os.open(path, flags, 0o600)
    with os.fdopen(fd, "w") as handle:
        handle.write(text)
    os.chmod(path, 0o600)


def _ensure_symlink(repo_root: Path, compose_env: Path) -> None:
    link = repo_root / "deploy/local-sit/.env"
    if link.is_symlink() and Path(os.readlink(link)) == compose_env:
        return
    if link.exists() or link.is_symlink():
        link.unlink()
    link.symlink_to(compose_env)


if __name__ == "__main__":
    raise SystemExit(main())
